function toCompanyRow(input: CompanyInput, group: CompanyGroup): CompanySeedRow {
  const item = typeof input === "string" ? { name: input } : input;
  const name = item.name.trim();
  const slug = item.slug ?? SLUG_OVERRIDES[name] ?? slugifyCompanyName(name);

  return {
    name,
    slug,
    city: "city" in item ? item.city ?? null : group.city ?? null,
    industry: group.industry,
    verified: item.verified ?? false,
  };
}

function buildCompanySeed(): CompanySeedRow[] {
  return GROUPS.flatMap((group) =>
    group.companies.map((item) => toCompanyRow(item, group))
  );
}

export const COMPANIES_UA_500 = buildCompanySeed();
